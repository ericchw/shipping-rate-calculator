import { test, expect } from "@playwright/test";
test("comparisons are saved once, viewed in a popup, restored and compared again", async ({ page }) => {
  test.setTimeout(60000);
  await page.clock.setFixedTime(new Date("2026-10-14T18:00:00Z"));
  const origin = new URL(test.info().project.use.baseURL!).origin;
  expect((await page.request.post("/sandbox/api/v1/auth/login", { headers:{Origin:origin}, data:{email:"group-user@example.invalid",password:"fixture-password-only",channel:"web"} })).ok()).toBeTruthy();
  await page.route("**/sandbox/api/v1/postal-suggestions?*", route => route.fulfill({json:{country:"CA",lookupCode:"V6V",precision:"area",suggestions:[],message:null}}));
  await page.goto("/sandbox/rate");
  await expect(page.getByRole("checkbox", { name:"FedEx",exact:true })).toBeChecked();
  await page.getByRole("checkbox", { name:"FedEx",exact:true }).uncheck();
  for(const [prefix, city, region, postal] of [["from","Richmond","BC","V6V2K9"],["to","Toronto","ON","M5V2T6"]]) {
    await page.locator(`#${prefix}-city`).fill(city); await page.locator(`#${prefix}-region`).fill(region); await page.locator(`#${prefix}-postal_code`).fill(postal);
  }
  await page.locator("#weight").fill("5");
  await page.getByLabel("Ship date",{exact:true}).fill("2026-01-01");
  await page.getByLabel("Coverage / declared value (CAD)").fill("100");
  await page.getByRole("button",{name:"Compare rates",exact:true}).click();
  await expect(page.getByText("QUOTES READY",{exact:true})).toBeVisible();
  await expect(page.getByRole("button",{name:"Rate logs",exact:true})).toBeEnabled();
  await page.reload();
  await page.getByRole("button",{name:"Rate logs",exact:true}).click();
  const dialog=page.getByRole("dialog");
  await expect(dialog).toBeVisible();
  await expect(dialog.getByText("1 saved comparison",{exact:false})).toBeVisible();
  await dialog.getByRole("combobox",{name:"Rate log page size",exact:true}).selectOption("10");
  await dialog.getByRole("button",{name:"View comparison from Richmond to Toronto",exact:true}).click();
  await expect(dialog.getByRole("heading",{name:"Saved rate comparison",exact:true})).toBeVisible();
  await expect(dialog.locator(".history-rate-cards article")).not.toHaveCount(0);
  await expect(dialog.getByText("BC · Richmond · V6V2K9",{exact:true})).toBeVisible();
  await expect(dialog.getByText("Ship date: 2026-01-01",{exact:true})).toBeVisible();
  await page.screenshot({path:test.info().outputPath("rate-log-popup.png"),fullPage:true});
  await dialog.getByRole("button",{name:"Load shipping details",exact:true}).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.locator("#from-city")).toHaveValue("Richmond");
  await expect(page.locator("#to-city")).toHaveValue("Toronto");
  await expect(page.locator("#weight")).toHaveValue("5");
  await expect(page.locator("#length")).toHaveValue("0");
  await expect(page.getByLabel("Coverage / declared value (CAD)")).toHaveValue("100");
  await expect(page.getByLabel("Ship date",{exact:true})).toHaveValue("2026-10-14");
  await expect(page.getByRole("checkbox",{name:"FedEx",exact:true})).not.toBeChecked();
  await expect(page.locator(".toast").filter({hasText:"Past ship date updated to today"})).toBeVisible();
  await page.getByRole("button",{name:"Compare rates",exact:true}).click();
  await expect(page.getByText("QUOTES READY",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Rate logs",exact:true}).click();
  await expect(dialog.getByText("2 saved comparisons",{exact:false})).toBeVisible();
  await dialog.getByRole("button",{name:"Delete comparison from Richmond to Toronto",exact:true}).first().click();
  const confirmation=page.getByRole("alertdialog",{name:"Delete this rate log?",exact:true});
  await expect(confirmation).toBeVisible();
  await expect(confirmation.getByRole("button",{name:"Cancel",exact:true})).toBeFocused();
  await page.keyboard.press("Tab");
  await expect(confirmation.getByRole("button",{name:"Yes, delete log",exact:true})).toBeFocused();
  await page.keyboard.press("Tab");
  await expect(confirmation.getByRole("button",{name:"Cancel",exact:true})).toBeFocused();
  await confirmation.getByRole("button",{name:"Cancel",exact:true}).click();
  await expect(dialog.getByText("2 saved comparisons",{exact:false})).toBeVisible();
  await dialog.getByRole("button",{name:"Delete comparison from Richmond to Toronto",exact:true}).first().click();
  await confirmation.getByRole("button",{name:"Yes, delete log",exact:true}).click();
  await expect(confirmation).toHaveCount(0);
  await expect(dialog.getByText("1 saved comparison",{exact:false})).toBeVisible();
  await dialog.getByRole("button",{name:"View comparison from Richmond to Toronto",exact:true}).click();
  await dialog.getByRole("button",{name:"Delete log",exact:true}).click();
  await confirmation.getByRole("button",{name:"Yes, delete log",exact:true}).click();
  await expect(dialog.getByText("0 saved comparisons",{exact:false})).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole("button",{name:"Rate logs",exact:true})).toBeFocused();
});
