import { test, expect } from "@playwright/test";
test("four interface languages and dark mode persist across pages and follow the system when selected", async ({ page }) => {
  test.setTimeout(90000);
  await page.route("**/sandbox/api/v1/postal-suggestions?*", route => route.fulfill({json:{country:"CA",lookupCode:"",precision:"area",suggestions:[],message:null}}));
  await page.emulateMedia({ colorScheme:"light" });
  await page.goto("/sandbox/login");
  const language = page.locator('.appearance-controls select').nth(0), theme = page.locator('.theme-toggle');
  await expect(page.getByRole("heading",{name:"Sign in",exact:true})).toBeVisible();
  await expect(theme).toHaveAccessibleName("System theme · Switch to dark mode");
  await page.emulateMedia({colorScheme:"dark"});
  await expect(page.locator("html")).toHaveAttribute("data-theme","dark");
  await page.emulateMedia({colorScheme:"light"});
  await expect(page.locator("html")).toHaveAttribute("data-theme","light");
  await theme.click();
  await expect(page.locator("html")).toHaveAttribute("data-theme","dark");
  const background = await page.locator("body").evaluate(element => getComputedStyle(element).backgroundColor);
  expect(background).not.toBe("rgb(243, 248, 252)");
  await language.selectOption("fr");
  await expect(page.getByRole("heading",{name:"Connexion",exact:true})).toBeVisible();
  await expect(page.locator("html")).toHaveAttribute("lang","fr");
  await language.selectOption("zh-TW"); await expect(page.getByRole("heading",{name:"登入",exact:true})).toBeVisible();
  await language.selectOption("zh-CN"); await expect(page.getByRole("heading",{name:"登录",exact:true})).toBeVisible();
  await page.reload();
  await expect(page.locator("html")).toHaveAttribute("lang","zh-CN");
  await expect(page.locator("html")).toHaveAttribute("data-theme","dark");
  const origin = new URL(test.info().project.use.baseURL!).origin;
  expect((await page.request.post("/sandbox/api/v1/auth/login",{headers:{Origin:origin},data:{email:"e2e@example.invalid",password:"fixture-password-only",channel:"web"}})).ok()).toBeTruthy();
  await page.goto("/sandbox/rate");
  await expect(page.getByRole("heading",{name:"比较运费",exact:true})).toBeVisible();
  await expect(page.getByLabel("箱数",{exact:true})).toHaveValue("1");
  await expect(page.getByLabel("城市",{exact:true})).toHaveCount(2);
  await page.locator("#to-city").fill("Toronto");
  await language.selectOption("fr");
  await expect(page.getByRole("heading",{name:"Comparer les tarifs d’expédition",exact:true})).toBeVisible();
  await expect(page.locator("#to-city")).toHaveValue("Toronto");
  await language.selectOption("zh-CN");
  for (const [prefix,city,region,postal] of [["from","Richmond","BC","V6V2K9"],["to","Toronto","ON","M5V2T6"]]) {
    await page.locator(`#${prefix}-city`).fill(city); await page.locator(`#${prefix}-region`).fill(region); await page.locator(`#${prefix}-postal_code`).fill(postal);
  }
  await page.getByRole("button",{name:"比较运费",exact:true}).click();
  await expect(page.getByText("报价已就绪",{exact:true})).toBeVisible();
  await expect(page.getByRole("button",{name:"比较运费",exact:true})).toBeEnabled();
  const rowCount = await page.locator("tbody tr").count();
  expect(rowCount).toBeGreaterThan(0);
  await language.selectOption("fr");
  await expect(page.getByText("TARIFS DISPONIBLES",{exact:true})).toBeVisible();
  await expect(page.locator("tbody tr")).toHaveCount(rowCount);
  await language.selectOption("zh-CN");
  await page.getByRole("button",{name:"报价记录",exact:true}).click();
  const dialog=page.getByRole("dialog");
  await expect(dialog).toBeVisible(); await dialog.locator(".history-record").first().click();
  await expect(dialog.getByRole("heading",{name:"已保存的报价比较",exact:true})).toBeVisible();
  await expect(dialog.locator(".history-rate-cards article")).toHaveCount(rowCount);
  await page.screenshot({path:test.info().outputPath("logs-dark-chinese.png"),fullPage:true});
  await dialog.getByRole("button",{name:"关闭报价记录",exact:true}).click();
  await page.screenshot({path:test.info().outputPath("rates-dark-chinese.png"),fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.getByRole("link",{name:"设置",exact:true}).click();
  await expect(page.getByRole("tab",{name:"我的设置",exact:false})).toBeVisible();
  await page.getByRole("tab",{name:"公司组",exact:false}).click();
  await page.getByRole("tab",{name:"API 连接",exact:true}).click();
  await expect(page.getByRole("heading",{name:"承运商 API 设置",exact:true})).toBeVisible();
  await page.screenshot({path:test.info().outputPath("settings-dark-chinese.png"),fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.getByRole("link",{name:"标签",exact:true}).click();
  await expect(page.getByRole("heading",{name:"已生成的标签",exact:true})).toBeVisible();
  await theme.click();
  await theme.click();
  await expect(page.locator("html")).toHaveAttribute("data-theme","light");
  await page.emulateMedia({colorScheme:"dark"});
  await expect(page.locator("html")).toHaveAttribute("data-theme","dark");
  await language.selectOption("en");
  await expect(page.getByRole("heading",{name:"Generated labels",exact:true})).toBeVisible();
  await theme.click();
  await theme.click();
  await expect(page.locator("html")).toHaveAttribute("data-theme","light");
});
