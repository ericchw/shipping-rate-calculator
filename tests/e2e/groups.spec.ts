import { test, expect } from "@playwright/test";
const password = "fixture-password-only";
const origin = () => new URL(test.info().project.use.baseURL!).origin;
async function signIn(page: import("@playwright/test").Page, email = "group-admin@example.invalid") {
  const response = await page.request.post("/sandbox/api/v1/auth/login", { headers: { Origin: origin() }, data: { email, password, channel: "web" } });
  expect(response.ok()).toBeTruthy();
}
test("company settings have focused sections, assigned members and a working delete confirmation", async ({ page }) => {
  test.setTimeout(90000);
  await signIn(page); await page.goto("/sandbox/setting");
  await expect(page.getByRole("tab",{name:"My settings",exact:true})).toHaveAttribute("aria-selected","true");
  await page.getByRole("tab",{name:"Company groups",exact:false}).click();
  const directory=page.getByRole("complementary",{name:"Company groups",exact:true});
  await directory.getByRole("button",{name:"Add company",exact:true}).click();
  const name=`UI company ${test.info().project.name} ${Date.now()}`;
  await directory.getByLabel("Company name",{exact:true}).fill(name);
  const created=page.waitForResponse(response=>response.url().endsWith("/admin/groups")&&response.request().method()==="POST");
  await directory.getByRole("button",{name:"Create company",exact:true}).click();
  const groupId=(await (await created).json()).id;
  await expect(page.locator(".company-detail-heading h2")).toHaveText(name);
  await expect(page.getByRole("checkbox",{name:"Enable tracking and label generation",exact:true})).not.toBeChecked();
  await page.getByRole("checkbox",{name:"Enable tracking and label generation",exact:true}).check();
  await expect(page.locator(".toast").filter({hasText:"generation enabled"})).toBeVisible();
  await page.getByRole("tab",{name:"API connections",exact:true}).click();
  const loomis=page.locator(".carrier-setting-card").filter({has:page.getByRole("heading",{name:"Loomis Express",exact:true})});
  await loomis.getByLabel("Username",{exact:true}).fill("ui-company-user");
  await loomis.getByLabel("Password",{exact:true}).fill("ui-company-secret");
  await loomis.getByLabel("Account ID",{exact:true}).fill("ui-company-account");
  await loomis.getByRole("checkbox",{name:"Enabled",exact:true}).check();
  await loomis.getByRole("button",{name:"Save settings",exact:true}).click();
  await expect(loomis.getByRole("status").filter({hasText:"Settings saved to this company group."})).toBeVisible();
  await page.getByRole("tab",{name:"Overview",exact:true}).click();
  await page.locator(".company-profile-card").getByLabel("Company name",{exact:true}).fill(`${name} renamed`);
  await page.getByRole("button",{name:"Save name",exact:true}).click();
  await expect(page.locator(".company-detail-heading h2")).toHaveText(`${name} renamed`);
  await page.getByRole("tab",{name:/^Members/}).click();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.getByRole("button",{name:"+ Add user",exact:true}).click();
  const editor=page.getByRole("region",{name:"Add user",exact:true});
  const email=`ui-${test.info().project.name}-${Date.now()}@example.invalid`;
  await editor.getByLabel("Email",{exact:true}).fill(email); await editor.getByLabel("Password",{exact:true}).fill(password);
  await expect(editor.getByRole("combobox",{name:"User company group",exact:true})).toHaveValue(groupId);
  await editor.getByRole("button",{name:"Create user",exact:true}).click();
  await expect(page.locator(".users-table tr").filter({hasText:email})).toContainText(`${name} renamed`);
  await page.getByRole("tab",{name:"Users and access",exact:false}).click();
  await page.getByRole("searchbox",{name:"Find a user",exact:true}).fill(email);
  await expect(page.locator(".users-table tbody tr")).toHaveCount(1);
  await expect(page.locator(".users-table tbody tr")).toContainText("Web on");
  await page.getByRole("tab",{name:"Company groups",exact:false}).click();
  await directory.getByRole("button",{name:new RegExp(name)}).click();
  await page.getByRole("tab",{name:"Overview",exact:true}).click();
  await page.getByRole("button",{name:"Delete group",exact:true}).click();
  await page.getByRole("button",{name:"Yes, delete group",exact:true}).click();
  await expect(page.getByRole("alert").filter({hasText:"Move this company's members"})).toBeVisible();
  await page.getByRole("button",{name:"Cancel",exact:true}).click();
  await directory.getByRole("button",{name:"Add company",exact:true}).click();
  const empty=`Empty ${test.info().project.name} ${Date.now()}`;
  await directory.getByLabel("Company name",{exact:true}).fill(empty); await directory.getByRole("button",{name:"Create company",exact:true}).click();
  await expect(page.locator(".company-detail-heading h2")).toHaveText(empty);
  await page.getByRole("button",{name:"Delete group",exact:true}).click(); await page.getByRole("button",{name:"Cancel",exact:true}).click();
  await expect(directory.getByRole("button",{name:new RegExp(empty)})).toBeVisible();
  await page.getByRole("button",{name:"Delete group",exact:true}).click(); await page.getByRole("button",{name:"Yes, delete group",exact:true}).click();
  await expect(directory.getByRole("button",{name:new RegExp(empty)})).toHaveCount(0);
  await page.screenshot({path:test.info().outputPath("company-settings.png"),fullPage:true});
  await signIn(page,email); await page.goto("/sandbox/setting");
  await expect(page.getByRole("tab",{name:"Company groups",exact:false})).toHaveCount(0);
  await expect(page.locator(".membership-card h2")).toHaveText(`${name} renamed`);
  await expect(page.locator(".carrier-settings")).toHaveCount(0);
  expect((await page.request.put("/sandbox/api/v1/carrier-settings/sandbox/loomis",{headers:{Origin:origin()},data:{enabled:false}})).status()).toBe(403);
});
test("users share their company's saved labels while other companies cannot read them", async ({ page }) => {
  test.setTimeout(60000); await signIn(page,"group-user@example.invalid"); await page.goto("/sandbox/labels");
  await expect(page.getByText("Company group: Fixture company",{exact:true})).toBeVisible();
  await page.getByRole("cell").filter({hasText:"GROUP123"}).click();
  await expect(page.getByRole("heading",{name:"Label details",exact:true})).toBeVisible(); const labelPath=new URL(page.url()).pathname;
  await signIn(page,"group-colleague@example.invalid"); await page.goto(labelPath);
  await expect(page.getByRole("img",{name:/Loomis sandbox label GROUP1/})).toBeVisible();
  const download=page.waitForEvent("download"); await page.getByRole("link",{name:"Download PNG",exact:true}).click(); expect((await download).suggestedFilename()).toBe("loomis-sandbox-GROUP1-1.png");
  await signIn(page,"other-user@example.invalid"); await page.goto(labelPath); await expect(page.getByRole("alert").filter({hasText:"Label not found"})).toHaveText("Label not found");
  await page.goto("/sandbox/labels"); await expect(page.locator(".saved-label-row")).toHaveCount(0); await expect(page.getByRole("combobox",{name:"Labels company group",exact:true})).toHaveCount(0);
});
